CREATE TABLE topic (
                       id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name        VARCHAR(100) NOT NULL UNIQUE,
                       description VARCHAR(500)
);
CREATE TABLE question (
                          id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          topic_id           BIGINT        NOT NULL REFERENCES topic (id) ON DELETE CASCADE,
                          text               VARCHAR(1000) NOT NULL,
                          type               VARCHAR(20)   NOT NULL
                              CHECK (type IN ('SINGLE_CHOICE', 'MULTIPLE_CHOICE', 'TRUE_FALSE', 'FREE_TEXT')),
                          difficulty         VARCHAR(10)   NOT NULL
                              CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
                          points             INT           NOT NULL CHECK (points > 0),
                          time_limit_seconds INT           CHECK (time_limit_seconds > 0),
                          explanation        VARCHAR(2000)
);
CREATE INDEX idx_question_topic ON question (topic_id);
CREATE TABLE answer_option (
                               id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               question_id BIGINT       NOT NULL REFERENCES question (id) ON DELETE CASCADE,
                               text        VARCHAR(500) NOT NULL,
                               correct     BOOLEAN      NOT NULL
);
CREATE INDEX idx_answer_option_question ON answer_option (question_id);
CREATE TABLE accepted_answer (
                                 id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 question_id    BIGINT       NOT NULL REFERENCES question (id) ON DELETE CASCADE,
                                 text           VARCHAR(500) NOT NULL,
                                 case_sensitive BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_accepted_answer_question ON accepted_answer (question_id);
CREATE TABLE attempt (
                         id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         topic_id    BIGINT      NOT NULL REFERENCES topic (id),
                         started_at  TIMESTAMPTZ NOT NULL,
                         finished_at TIMESTAMPTZ,
                         total_score INT         NOT NULL DEFAULT 0,
                         max_score   INT         NOT NULL
);
CREATE INDEX idx_attempt_topic ON attempt (topic_id);
CREATE TABLE attempt_answer (
                                id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                attempt_id             BIGINT        NOT NULL REFERENCES attempt (id) ON DELETE CASCADE,
                                question_id            BIGINT        NOT NULL REFERENCES question (id),
                                question_text_snapshot VARCHAR(1000) NOT NULL,
                                free_text_answer       VARCHAR(500),
                                correct                BOOLEAN       NOT NULL,
                                points_awarded         INT           NOT NULL,
                                max_points             INT           NOT NULL,
                                answered_at            TIMESTAMPTZ   NOT NULL,
                                UNIQUE (attempt_id, question_id)
);-- Zwischentabelle für die Mehrfachauswahl bei Multiple Choice
CREATE TABLE attempt_answer_selected_option (
                                                attempt_answer_id BIGINT NOT NULL REFERENCES attempt_answer (id) ON DELETE CASCADE,
                                                answer_option_id  BIGINT NOT NULL REFERENCES answer_option (id),
                                                PRIMARY KEY (attempt_answer_id, answer_option_id)
);
